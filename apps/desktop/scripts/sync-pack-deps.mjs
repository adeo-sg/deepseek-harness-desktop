/**
 * Sync apps/desktop's `dependencies` with the FULL runtime closure the
 * packaged shell needs. electron-builder collects only the packages declared
 * in the app's `dependencies` (plus their non-peer `dependencies`); the
 * harness's Service Definition packages are peers of their implementations,
 * so every reachable peer must be declared explicitly or the packaged boot
 * fails with ERR_MODULE_NOT_FOUND. This computes the closure over the
 * workspace (vendor + packages) and reports the delta:
 *   node scripts/sync-pack-deps.mjs            # print missing entries
 *   node scripts/sync-pack-deps.mjs --write    # merge them into package.json
 * The generated list is a packaging fact; keep it current with this script.
 */

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('../../..', import.meta.url))
const MANIFEST_PATH = join(ROOT, 'apps', 'desktop', 'package.json')

/** Build the workspace name → package-dir map (vendor single-level + packages two-level). */
function workspaceMap() {
  const byName = new Map()
  const add = (pkgDir) => {
    const mf = join(pkgDir, 'package.json')
    try {
      if (!statSync(mf).isFile()) return
    } catch {
      return
    }
    const pkg = JSON.parse(readFileSync(mf, 'utf8'))
    if (typeof pkg.name === 'string') byName.set(pkg.name, pkgDir)
  }
  for (const entry of readdirSync(join(ROOT, 'vendor'))) {
    const dir = join(ROOT, 'vendor', entry)
    if (statSync(dir).isDirectory()) add(dir)
  }
  for (const group of readdirSync(join(ROOT, 'packages'))) {
    const groupDir = join(ROOT, 'packages', group)
    if (!statSync(groupDir).isDirectory()) continue
    for (const entry of readdirSync(groupDir)) {
      const dir = join(groupDir, entry)
      if (statSync(dir).isDirectory()) add(dir)
    }
  }
  return byName
}

/** BFS the declared deps through every workspace package's deps AND peers. */
function closureDeps(manifest, byName) {
  const queue = [...Object.keys(manifest.dependencies ?? {}).filter(name => byName.has(name))]
  const visited = new Set()
  const reachable = new Set()
  while (queue.length > 0) {
    const name = queue.shift()
    if (visited.has(name)) continue
    visited.add(name)
    const dir = byName.get(name)
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
    for (const dep of [...Object.keys(pkg.dependencies ?? {}), ...Object.keys(pkg.peerDependencies ?? {})]) {
      if (!dep.startsWith('@deepseek-ai/')) continue
      if (!byName.has(dep)) continue
      reachable.add(dep)
      queue.push(dep)
    }
  }
  return reachable
}

const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'))
const byName = workspaceMap()
const reachable = closureDeps(manifest, byName)
const declared = new Set(Object.keys(manifest.dependencies ?? {}))
const missing = [...reachable].filter(name => !declared.has(name)).sort()

if (process.argv.includes('--write')) {
  if (missing.length === 0) {
    console.log('sync-pack-deps: closure complete, no changes.')
  } else {
    const dependencies = {}
    for (const name of Object.keys(manifest.dependencies ?? {}).sort()) dependencies[name] = manifest.dependencies[name]
    for (const name of missing) dependencies[name] = 'workspace:^'
    manifest.dependencies = dependencies
    writeFileSync(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`)
    console.log(`sync-pack-deps: added ${missing.length} workspace dependency(ies) to ${MANIFEST_PATH}.`)
  }
} else if (missing.length > 0) {
  console.error(`sync-pack-deps: ${missing.length} workspace dependency(ies) missing from the packaged closure:`)
  for (const name of missing) console.error(`  ${name}`)
  console.error('run with --write to merge them (a packaging fact, regenerated by this script).')
  process.exitCode = 1
} else {
  console.log('sync-pack-deps: closure complete.')
}
